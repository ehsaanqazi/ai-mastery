/**
 * Regenerates the sidebar-style navigation in README.md from src/data/curriculum.ts.
 * Every item links to its page on the live site.
 *
 *   npm run readme
 */
import { existsSync, readFileSync, writeFileSync } from 'node:fs'
import { phases, pad } from '../src/data/curriculum.ts'

const SITE = 'https://ai-mastery-docs.netlify.app'
const README = new URL('../README.md', import.meta.url)
const CONTENT = new URL('../src/content/', import.meta.url)
const START = '<!-- SIDEBAR:START (generated by `npm run readme`, do not edit by hand) -->'
const END = '<!-- SIDEBAR:END -->'

const published = (moduleSlug: string, file: string) => existsSync(new URL(`${moduleSlug}/${file}.md`, CONTENT))

const lines: string[] = [
  START,
  '',
  `🏠 [Home](${SITE}/) &nbsp;·&nbsp; 🗺️ [Roadmap](${SITE}/roadmap) &nbsp;·&nbsp; 🔖 [My library](${SITE}/library)`,
  '',
]

for (const phase of phases) {
  lines.push(`### Phase ${pad(phase.n)} · ${phase.title}`, '', `<sub>${phase.months} · ${phase.blurb}</sub>`, '')

  for (const m of phase.modules) {
    const moduleUrl = `${SITE}/learn/${m.slug}`
    const live = m.topics.filter((t) => published(m.slug, t.slug)).length
    const badge = live === 0 ? 'soon' : `${live} lessons`

    lines.push(
      '<details>',
      `<summary><code>${String(m.n).padStart(2, ' ')}</code> <a href="${moduleUrl}"><b>${m.title}</b></a> <sub>${badge}</sub></summary>`,
      '',
    )
    for (const t of m.topics) {
      lines.push(published(m.slug, t.slug) ? `- [${t.title}](${moduleUrl}/${t.slug})` : `- ${t.title} _(soon)_`)
    }
    if (published(m.slug, 'assessment')) lines.push(`- 📝 **[Module quiz](${moduleUrl}/assessment)**`)
    lines.push('', '</details>', '')
  }
}

lines.push(END)

const readme = readFileSync(README, 'utf8')
const startTag = readme.indexOf('<!-- SIDEBAR:START')
const endTag = readme.indexOf(END)
if (startTag === -1 || endTag === -1) throw new Error('README.md is missing the SIDEBAR:START / SIDEBAR:END markers')

writeFileSync(README, readme.slice(0, startTag) + lines.join('\n') + readme.slice(endTag + END.length))
console.log('README.md navigation updated')
